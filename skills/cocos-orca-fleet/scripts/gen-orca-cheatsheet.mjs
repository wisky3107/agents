#!/usr/bin/env node
/**
 * gen-orca-cheatsheet.mjs — version-stamped `orca` command cheatsheets generated from
 * `orca agent-context --json`, so agents read one compact file instead of running `--help`
 * (M3 of docs/plans/2026-10-01-coordinator-token-optimization).
 *
 *   node gen-orca-cheatsheet.mjs            write reference/orca/cheatsheet*.md (coordinator, producer, worker, browser)
 *   node gen-orca-cheatsheet.mjs --check    exit 1 with one line when the installed orca differs from the stamp
 *                                           (or when it cannot produce cheatsheets at all: no agent-context)
 *   node gen-orca-cheatsheet.mjs --coverage list `orca …` commands the pipeline skills name that no cheatsheet has
 *
 * Never edit the generated files by hand: change GROUPS here and rerun.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// Lives in cocos-orca-fleet (pipeline-owned), not orca-cli: `orca skills update` may replace that skill.
const REF = process.env.ORCA_CHEATSHEET_DIR || path.join(HERE, '..', 'reference', 'orca'); // env: tests only
const OUT = {
  coordinator: path.join(REF, 'cheatsheet.md'),
  producer: path.join(REF, 'cheatsheet-producer.md'),
  worker: path.join(REF, 'cheatsheet-worker.md'),
  browser: path.join(REF, 'cheatsheet-browser.md'),
};
const STAMP_RE = /<!-- generated by gen-orca-cheatsheet\.mjs from orca (.+?) \(agent-context/;

// One file per role, so each agent reads only its commands. Selection: what the producer / fleet /
// lane prompts use, plus the --help targets most seen in transcripts (tools/token-report, 2026-09-24..10-01).
// Notes a role cannot act on are dropped per role (dropNotes); platform-only notes everywhere.
const TERMINAL = ['terminal create', 'terminal list', 'terminal show', 'terminal wait', 'terminal read', 'terminal send', 'terminal close'];
const GROUPS = {
  coordinator: {
    title: 'fleet coordinator — Run, Tasks, workers, messages, terminals, worktrees',
    regenerate: true,
    // this pipeline runs workers locally in Orca worktrees: remote host / SSH placement notes are noise
    dropNotes: /--host\b|--on\b|--project\b|paired Orca server|\bremote\b|\bSSH\b|\bWSL\b|project host/i,
    groups: [
      ['Run and Tasks', [
        'orchestration run-create', 'orchestration run-use', 'orchestration run-current', 'orchestration run-list',
        'orchestration run-show', 'orchestration task-create', 'orchestration task-list', 'orchestration task-update',
        'orchestration dispatch', 'orchestration dispatch-show',
      ]],
      ['Workers', [
        'orchestration worker-start', 'orchestration worker-show', 'orchestration worker-read', 'orchestration worker-list',
        'orchestration worker-release', 'orchestration worker-retain',
      ]],
      ['Recovery (read the recovery reference first: see your skill)', ['orchestration worker-stop', 'orchestration worker-abandon']],
      ['Messages and gates', [
        'orchestration check', 'orchestration send', 'orchestration reply', 'orchestration ask', 'orchestration inbox',
        'orchestration gate-create', 'orchestration gate-resolve', 'orchestration gate-list',
      ]],
      ['Terminals', TERMINAL],
      ['Worktrees and runtime', ['worktree create', 'worktree list', 'worktree rm', 'status', 'skills get']],
    ],
  },
  producer: {
    title: 'game-producer — lane terminals, read-only Run state, worktrees',
    regenerate: true,
    dropNotes: /--host\b|--on\b|--project\b|paired Orca server|\bremote\b|\bSSH\b|\bWSL\b|project host/i,
    groups: [
      ['Terminals', TERMINAL],
      ['Lane Runs (read-only for the producer)', [
        'orchestration run-list', 'orchestration run-show', 'orchestration inbox', 'orchestration gate-list', 'orchestration ask',
      ]],
      ['Worktrees', ['worktree list', 'worktree rm']],
    ],
  },
  worker: {
    title: 'dispatched worker — reporting to the coordinator',
    dropNotes: /Group addresses|Run groups|Nested coordinators|@worktree/,
    groups: [['Messages', ['orchestration send', 'orchestration ask', 'orchestration check', 'orchestration reply']]],
  },
  browser: {
    title: 'embedded browser (reviewer / integrator)',
    groups: [
      ['Tabs and navigation', ['tab list', 'tab current', 'tab show', 'tab create', 'tab switch', 'tab close', 'goto', 'reload', 'back', 'forward', 'wait']],
      ['Reading the page', ['screenshot', 'full-screenshot', 'snapshot', 'eval', 'exec', 'console', 'network', 'get', 'is', 'find']],
      ['Device', ['viewport', 'set device', 'set media']],
      ['Input', ['click', 'dblclick', 'hover', 'fill', 'type', 'keypress', 'inserttext', 'select', 'check', 'uncheck', 'focus',
        'scroll', 'scrollintoview', 'drag', 'mouse move', 'mouse down', 'mouse up', 'mouse wheel', 'dialog accept', 'dialog dismiss']],
    ],
  },
};
// Bootstrap-chat commands (new-cocos-game Step 1-3) that no lane runs.
const COVERAGE_IGNORE = new Set(['repo add', 'claude-teams', 'open']);

// Skill files whose `orca …` commands the cheatsheets must cover (`--coverage`).
const COVERAGE_FILES = [
  '../../game-producer/SKILL.md', '../../game-producer/reference', '../../cocos-orca-fleet/SKILL.md',
  '../../cocos-orca-fleet/reference', '../../cocos-asset-gen/reference/worker-prompts-art.md',
  '../../new-cocos-game/SKILL.md', '../../store-game-clone/SKILL.md', '../../store-game-clone/reference',
];

function fail(msg, code = 2) {
  console.error(`gen-orca-cheatsheet: ${msg}`);
  process.exit(code);
}

function orca(args) {
  const r = spawnSync('orca', args, { encoding: 'utf8' });
  if (r.error?.code === 'ENOENT') fail('orca is not on PATH');
  if (r.status !== 0) fail(`orca ${args.join(' ')} failed: ${(r.stderr || r.stdout || '').trim()}`);
  return r.stdout;
}

const orcaVersion = () => orca(['--version']).trim();

function schema() {
  const d = JSON.parse(orca(['agent-context', '--json']));
  return { version: d.schemaVersion, byName: new Map(d.commands.map((c) => [c.command, c])) };
}

// Notes about another platform only ("On Windows …") cost tokens and help nobody here.
const SKIP_NOTE = /^On Windows\b/i;

function renderCommand(c, dropNotes) {
  const [sig, ...detail] = c.usage.split('\n');
  const lines = [`### \`orca ${c.command}\``, c.summary ? `${c.summary.replace(/\.?$/, '.')}` : '', '```', sig.trim()];
  for (const d of detail) if (d.trim()) lines.push(d.replace(/^\s{0,2}/, ''));
  lines.push('```');
  for (const n of c.notes || []) if (!SKIP_NOTE.test(n) && !(dropNotes && dropNotes.test(n))) lines.push(`- ${n}`);
  const ex = (c.examples || []).find((e) => !SKIP_NOTE.test(e));
  if (ex) lines.push(`- e.g. \`${ex.replace(/^\$\s*/, '')}\``);
  return lines.filter((l) => l !== '').join('\n');
}

function render(kind, { title: roleTitle, groups, regenerate, dropNotes }, s, version) {
  const missing = [];
  const title = `# orca cheatsheet — ${roleTitle}`;
  const parts = [
    `<!-- generated by gen-orca-cheatsheet.mjs from orca ${version} (agent-context schema v${s.version}); do not edit — rerun the script -->`,
    title,
    '',
    `Flags and notes for orca ${version}, straight from \`orca agent-context --json\`. Use this instead of`,
    regenerate
      ? '`orca … --help`. Before the first `orca` call run `node ~/.agents/skills/cocos-orca-fleet/scripts/gen-orca-cheatsheet.mjs --check`;\n'
        + 'if it says stale, run the command it prints. `--help` only for a command missing here. Every command takes `--json`.'
      : '`orca … --help`. A command missing here, or an `orca --version` other than the one above: use that command\'s `--help`.\n'
        + 'Every command takes `--json`.',
    kind === 'browser'
      ? 'Browser commands act on the Orca embedded browser; `orca tab list` first, then target by `--page <id>` where the command takes it.'
      : 'Protocol (what to do, not which flags): your skill or spec; at an action gate it names, `orca skills get orchestration --reference references/<file>.md`.',
  ];
  for (const [heading, names] of groups) {
    parts.push('', `## ${heading}`, '');
    for (const n of names) {
      const c = s.byName.get(n);
      if (!c) {
        missing.push(n);
        continue;
      }
      parts.push(renderCommand(c, dropNotes), '');
    }
  }
  return { text: parts.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n', missing };
}

function stampedVersion(file) {
  try {
    return fs.readFileSync(file, 'utf8').match(STAMP_RE)?.[1] || null;
  } catch {
    return null;
  }
}

function listCoverageFiles() {
  const out = [];
  for (const rel of COVERAGE_FILES) {
    const p = path.resolve(HERE, rel);
    if (!fs.existsSync(p)) continue;
    if (fs.statSync(p).isDirectory()) {
      for (const f of fs.readdirSync(p)) if (f.endsWith('.md')) out.push(path.join(p, f));
    } else out.push(p);
  }
  return out;
}

function coverage(s) {
  const covered = new Set([...COVERAGE_IGNORE, ...Object.values(GROUPS).flatMap((r) => r.groups.flatMap(([, names]) => names))]);
  const used = new Map();
  for (const f of listCoverageFiles()) {
    const text = fs.readFileSync(f, 'utf8');
    for (const m of text.matchAll(/\borca\s+([a-z][a-z-]*)(?:\s+([a-z][a-z-]*))?/g)) {
      const two = m[2] ? `${m[1]} ${m[2]}` : null;
      const name = two && s.byName.has(two) ? two : s.byName.has(m[1]) ? m[1] : null;
      if (name && !covered.has(name)) used.set(name, [...(used.get(name) || []), path.relative(path.resolve(HERE, '../..'), f)]);
    }
  }
  return [...used].map(([name, files]) => ({ name, files: [...new Set(files)] }));
}

function writeAtomic(file, text) {
  const tmp = `${file}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
}

function main() {
  const argv = process.argv.slice(2);
  const known = new Set(['--check', '--coverage']);
  const bad = argv.filter((a) => !known.has(a));
  if (bad.length || argv.length > 1) fail(`usage: gen-orca-cheatsheet.mjs [--check | --coverage] (got: ${argv.join(' ')})`);
  const args = new Set(argv);
  const version = orcaVersion();
  if (args.has('--check')) {
    const stale = Object.values(OUT).filter((f) => stampedVersion(f) !== version);
    if (!stale.length) return;
    const ctx = spawnSync('orca', ['agent-context', '--json'], { encoding: 'utf8' });
    if (ctx.status !== 0) {
      console.log(`cheatsheet stale and orca ${version} has no agent-context: use \`orca <command> --help\``);
    } else {
      console.log(`cheatsheet stale (orca ${version}; ${stale.map((f) => `${path.basename(f)}=${stampedVersion(f) || 'missing'}`).join(', ')}) → node ${path.join(HERE, 'gen-orca-cheatsheet.mjs')}`);
    }
    process.exit(1);
  }
  const s = schema();
  if (args.has('--coverage')) {
    const gaps = coverage(s);
    for (const g of gaps) console.log(`${g.name}\t${g.files.join(', ')}`);
    process.exit(gaps.length ? 1 : 0);
  }
  fs.mkdirSync(REF, { recursive: true });
  for (const [kind, role] of Object.entries(GROUPS)) {
    const { text, missing } = render(kind, role, s, version);
    writeAtomic(OUT[kind], text);
    console.log(`${path.basename(OUT[kind])}: ${text.length} bytes${missing.length ? `; not in orca ${version}: ${missing.join(', ')}` : ''}`);
  }
}

main();
